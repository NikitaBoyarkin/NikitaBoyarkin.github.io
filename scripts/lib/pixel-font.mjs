// 5x7 bitmap font for the pixel-art OG banners.
//
// One line per glyph: seven rows of five cells, '/' between rows, '#' = ink.
// Capital height is the full seven rows; lowercase sits on rows 2..6 so
// descenders (g, p, q, y, д, р, у, ф, ц, щ) use rows 5..6. A glyph may carry an
// extra row ABOVE the capital box (OVER) for Ё and Й.
//
// Advance is five cells with no inter-glyph gap. That is not a style choice:
// «Product / Data Analyst» is 19 glyphs + 3 spaces. At five cells it measures
// 104 cells; a one-cell gap would make it 132 and it would not fit the 129-cell
// column at block 5. The gap is paid for by the glyph's own right column, which
// is blank in every glyph here.
//
// No glyph is wider than five cells, and none is kerned. This is a bitmap
// font, not a typesetter: an even grid is the whole point.

