/** Throws on a character the font cannot paint — a silent fallback would ship a hole. */
export function assertCovered(text) {
  for (const ch of String(text)) {
    if (!(ch in G)) throw new Error(`pixel font: no glyph for ${JSON.stringify(ch)} (U+${ch.codePointAt(0).toString(16).toUpperCase()})`);
  }
}

/** Width of `text` in cells, at native size. */
export function measure(text) {
  let w = 0;
  for (const ch of String(text)) w += NARROW[ch] ?? ADVANCE;
  return w;
}

function rowsOf(ch) {
  if (!(ch in G)) throw new Error(`pixel font: no glyph for ${JSON.stringify(ch)}`);
  return G[ch].split('/');
}

/**
 * SVG `<rect>` runs for `text`, origin at the top-left cell.
 *
 * Horizontal runs of ink are merged per row (never across rows), so a glyph edge
 * never sits inside a cell: the rasteriser has nothing to anti-alias, and the
 * block upscale later stays exact.
 */
export function glyphRects(text, x0, y0, { scale = 1, fill = '#000', advanceGap = 0 } = {}) {
  const out = [];
  let pen = x0;
  for (const ch of String(text)) {
    const rows = rowsOf(ch);
    const yTop = ch in OVER ? y0 - scale : y0;
    if (ch in OVER) {
      for (const [r, bits] of [OVER[ch]].entries()) {
        out.push(...runs(bits, pen, yTop + r * scale, scale, fill));
      }
    }
    for (let r = 0; r < GLYPH_H; r++) {
      const bits = rows[r] ?? '.....';
      out.push(...runs(bits, pen, y0 + r * scale, scale, fill));
    }
    pen += ((NARROW[ch] ?? ADVANCE) + (ch === ' ' ? 0 : advanceGap)) * scale;
  }
  return out;
}

function runs(bits, x, y, scale, fill) {
  const out = [];
  let i = 0;
  while (i < bits.length) {
    if (bits[i] !== '#') {
      i++;
      continue;
    }
    let j = i;
    while (j < bits.length && bits[j] === '#') j++;
    out.push(`<rect x="${x + i * scale}" y="${y}" width="${(j - i) * scale}" height="${scale}" fill="${fill}"/>`);
    i = j;
  }
  return out;
}

