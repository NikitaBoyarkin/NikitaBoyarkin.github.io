// Graph builder for the Matemarketing 2026 programme. Ported from lib/graph.ts
// (same GraphData shape, so the site's graph components render it unchanged).
//
// Edge model comes from the data, not the imagination: of 91 talks, 94 lectors
// appear exactly once (zero shared-lector edges) and text similarity tops out at
// cosine 0.13 — so the graph is built on the two signals that actually exist:
// the event's own tracks and derived theme tags.
//
// Only the first of those two is a hierarchy. The 11 theme tags cover up to 52
// of 91 talks each (`ai` 52, `product` 44, `metrics` 32 — 57/48/35 % of the
// programme), so as hubs they touch half the graph: the old full graph carried
// 257 theme edges plus 343 talk↔talk edges (talk pairs sharing at least three
// themes), 703 in all with the 103 core edges, and rendered as one knot with
// 24 always-on labels stacked on each other. Keeping the themes at a
// lower weight does not help — the force layout's ideal edge length only moves
// from 100 px (w=0.5) to 112 px (w=0.35) — so the graph keeps one level of
// grouping: `buildTalksGraph` returns the star the data defends, event → 12
// tracks → 91 talks with core edges only (103 edges, no theme or talk↔talk
// edges), and the themes moved one level down into the per-track mini-graphs,
// where they describe one track instead of the whole programme. The page draws
// the top of that star (`overviewGraph`) because 104 nodes overflow the
// renderer's force layout; see the note on that function.
import type { GraphData, GraphNode, GraphLink } from './graph';

export interface TalksTheme {
  id: string;
  label: string;
  labelEn: string;
}

export interface TalksTalk {
  id: number;
  title: string;
  hall: string;
  hallSlug: string;
  dayId: number;
  start: string;
  end: string;
  trackName: string;
  trackSlug: string;
  /** Numeric track id from the feed — the key shared with `mm-program-page`. */
  trackId: number;
  lectors: { name: string; role: string }[];
  short: string;
  themes: string[];
}

export interface TalksData {
  event: { id: number; name: string; startDate: string; endDate: string };
  themes: TalksTheme[];
  tracks: { id: number; name: string; slug: string }[];
  halls: { id: number; name: string; slug: string }[];
  days: { id: number; name: string; date: string }[];
  talks: TalksTalk[];
}

/** EN overlay generated by `scripts/sync-talks-data.mjs` from the source
 *  project's own `program.en.json`: the only two things that project
 *  translates. Everything else (halls, days, blurbs) has no EN copy, so the EN
 *  page falls back to the RU value rather than dropping it — the same RU-fallback
 *  convention `mergePostsForLocale` (lib/graph.ts) uses for untranslated posts. */
export interface TalksOverlay {
  /** RU track name → EN track name. Keyed by name, not slug: the source keys it
   *  that way, and the names are the programme's own vocabulary. */
  tracks?: Record<string, string>;
  /** Talk id as a string → EN title. */
  talkTitles?: Record<string, string>;
}

export const UNTRACKED = 'untracked';

/** Synthetic center node for the talks graph (the event, not a person). */
export const EVENT_ID = 'event:program';

/** The centre of the graph is the programme itself, so it points at the source
 *  of the data rather than back at this page. Same URL in both locales — the
 *  programme page has no EN build. */
export const PROGRAM_URL = 'https://nikitaboyarkin.github.io/mm-program-page/';

export const TRACK_LABEL = { ru: 'Без трека', en: 'Untracked' } as const;

/** Weight of a theme edge inside a track mini-graph. Low on purpose: a theme
 *  groups a talk, it is not its parent. */
export const THEME_WEIGHT = 0.35;

/** A theme becomes a hub inside one track only when that track is actually
 *  about it: at least MIN_THEME_TALKS of its talks and MIN_THEME_SHARE of them
 *  mention the theme, top MAX_TRACK_THEMES by breadth. Without the floor the
 *  «Без трека» bucket (27 talks) inherited all eleven themes and reproduced the
 *  old knot at a smaller scale. */
export const MIN_THEME_TALKS = 2;
export const MIN_THEME_SHARE = 0.4;
export const MAX_TRACK_THEMES = 4;

/** EN talk title when the overlay carries a non-empty one, RU title otherwise.
 *  An empty string in the overlay means "not translated", not "no title". */
export function talkTitle(
  talk: { id: number; title: string },
  lang: 'ru' | 'en' = 'ru',
  overlay?: TalksOverlay,
): string {
  if (lang !== 'en') return talk.title;
  const en = overlay?.talkTitles?.[String(talk.id)];
  return en?.trim() ? en : talk.title;
}

/** EN track name when the overlay carries one, RU name otherwise. */
export function trackName(
  name: string,
  lang: 'ru' | 'en' = 'ru',
  overlay?: TalksOverlay,
): string {
  if (lang !== 'en') return name;
  const en = overlay?.tracks?.[name];
  return en?.trim() ? en : name;
}

export function buildTalksGraph(
  data: TalksData,
  lang: 'ru' | 'en' = 'ru',
  overlay?: TalksOverlay,
): GraphData {
  const isEn = lang === 'en';
  const prefix = isEn ? 'en/' : '';
  const nodes: GraphNode[] = [];
  const links: GraphLink[] = [];
  const seen = new Set<string>();
  const linkKeys = new Set<string>();

  const addNode = (n: GraphNode) => {
    if (seen.has(n.id)) return;
    seen.add(n.id);
    nodes.push(n);
  };
  const addLink = (a: string, b: string, weight: number, type: GraphLink['type']) => {
    if (a === b || !seen.has(a) || !seen.has(b)) return;
    const key = [a, b].sort().join('\u0000');
    if (linkKeys.has(key)) return;
    linkKeys.add(key);
    links.push({ source: a, target: b, weight, type });
  };

  const titleOf = (talk: TalksTalk) => talkTitle(talk, lang, overlay);

  // One center for the radial reading: the event itself, so tracks hang off it.
  addNode({
    id: EVENT_ID,
    label: data.event.name,
    group: 'event',
    section: 'talks',
    url: PROGRAM_URL,
    size: 13,
  });

  // Tracks present in the programme, plus a synthetic bucket for the ~30% of
  // talks the source feed leaves without a track (all of online-day).
  const trackSlugs = new Map<string, string>();
  for (const t of data.tracks) trackSlugs.set(t.slug, t.name);
  if (data.talks.some((t) => !t.trackSlug)) {
    trackSlugs.set(UNTRACKED, isEn ? TRACK_LABEL.en : TRACK_LABEL.ru);
  }
  for (const [slug, name] of trackSlugs) {
    addNode({
      id: `track:${slug}`,
      label: slug === UNTRACKED ? name : trackName(name, lang, overlay),
      group: 'track',
      section: 'track',
      url: `${prefix}talks/#track-${slug}`,
      size: 11,
    });
    addLink(EVENT_ID, `track:${slug}`, 1, 'core');
  }

  for (const talk of data.talks) {
    addNode({
      id: `talk:${talk.id}`,
      label: titleOf(talk),
      group: talk.trackSlug || UNTRACKED,
      section: 'talks',
      url: `${prefix}talks/#t${talk.id}`,
      size: 5,
    });
  }

  // The full graph is one level of grouping, not two: theme edges (`topic`) and
  // the talk↔talk mesh (`shared`) live in the track mini-graphs / the Themes
  // section, because at programme scale they are what made the graph unreadable.
  for (const talk of data.talks) {
    addLink(`track:${talk.trackSlug || UNTRACKED}`, `talk:${talk.id}`, 1, 'core');
  }

  return { nodes, links };
}

/** The top graph the page draws: the event and its tracks, nothing else.
 *
 *  `buildTalksGraph` still returns the whole star (event → 12 tracks → 91
 *  talks), but that is 104 nodes and the force layout in `ProjectGraph.astro`
 *  cannot lay it out: seeded on one ring of radius min(w,h)*0.3 the nodes start
 *  ~13 px apart, so the pairwise repulsion (charge = 2200·√N, no distance cap)
 *  blows the layout apart in the first frame and the margin clamp parks the
 *  nodes in the corners. Replaying that exact tick loop at 974×720: 82 of 104
 *  nodes end on the margin, 709 pairs closer than 8 px, min distance 0 — and a
 *  1400 px-tall canvas still leaves 51 clamped. At ≤ 50 nodes it is 0
 *  coincident pairs; a 13-node event/track star lays out cleanly (min distance
 *  62 px). Talks therefore stay one level down, in the per-track mini-graphs,
 *  where each one is small enough to render and carries its own theme hubs.
 *
 *  The links are re-weighted here for spacing, not for meaning: the layout's
 *  ideal edge length is `60 + 80·(1 - weight)`, which puts the ring ~62 px from
 *  the centre at weight 1 — close enough for the centre label to run into the
 *  track label sitting at 3 o'clock. At 0.5 the ring sits ~100 px out and the
 *  two labels clear each other. */
const OVERVIEW_LINK_WEIGHT = 0.5;

export function overviewGraph(graph: GraphData): GraphData {
  const keep = new Set(
    graph.nodes.filter((n) => n.id === EVENT_ID || n.section === 'track').map((n) => n.id),
  );
  return {
    nodes: graph.nodes.filter((n) => keep.has(n.id)),
    links: graph.links
      .filter((l) => keep.has(l.source) && keep.has(l.target))
      .map((l) => ({ ...l, weight: Math.min(l.weight, OVERVIEW_LINK_WEIGHT) })),
  };
}

/** Talks belonging to one track, in programme order. Drives the per-track
 *  mini-graph and its list. */
export function talksOfTrack(data: TalksData, slug: string): TalksTalk[] {
  const key = slug === UNTRACKED ? '' : slug;
  return data.talks.filter((t) => t.trackSlug === key);
}

/** Mini-graph for one track: its hub, its talks and the direct talk↔talk
 *  edges among them. Theme nodes are left out — at one hop they would flood
 *  every mini-graph with the same eleven hubs. */
export function trackSubgraph(graph: GraphData, slug: string): GraphData {
  const hub = `track:${slug}`;
  const ids = new Set<string>([hub]);
  for (const n of graph.nodes) {
    if (n.id.startsWith('talk:') && n.group === slug) ids.add(n.id);
  }
  return {
    nodes: graph.nodes.filter((n) => ids.has(n.id)),
    links: graph.links.filter((l) => ids.has(l.source) && ids.has(l.target)),
  };
}

/** The mini-graph the page actually renders for one track: its hub, its talks,
 *  and the themes that *characterise* the track (see MIN_THEME_SHARE). This is
 *  where the theme layer lives now that the full graph is a single-level star.
 *  Talk↔talk mesh edges are not rebuilt here on purpose: two talks that share
 *  three themes both hang off the same theme hubs, which already draws that
 *  relation — and as a mesh it was 343 edges of noise. */
export function trackGraph(
  graph: GraphData,
  data: TalksData,
  slug: string,
  lang: 'ru' | 'en' = 'ru',
): GraphData {
  const base = trackSubgraph(graph, slug);
  const talks = talksOfTrack(data, slug);
  if (talks.length === 0) return base;

  const mentions = new Map<string, number>();
  for (const talk of talks) {
    for (const th of talk.themes) mentions.set(th, (mentions.get(th) ?? 0) + 1);
  }
  const floor = Math.max(MIN_THEME_TALKS, Math.ceil(talks.length * MIN_THEME_SHARE));
  const hubs = [...mentions.entries()]
    .filter(([, n]) => n >= floor)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, MAX_TRACK_THEMES)
    .map(([id]) => id);

  const isEn = lang === 'en';
  const prefix = isEn ? 'en/' : '';
  const themeById = new Map(data.themes.map((th) => [th.id, th]));
  const nodes = [...base.nodes];
  const links = [...base.links];
  for (const id of hubs) {
    const theme = themeById.get(id);
    if (!theme) continue; // a tag with no label is not worth a node
    nodes.push({
      id: `theme:${id}`,
      label: isEn ? theme.labelEn : theme.label,
      group: 'theme',
      section: 'theme',
      url: `${prefix}talks/#theme-${id}`,
      size: 9,
    });
    for (const talk of talks) {
      if (talk.themes.includes(id)) {
        links.push({ source: `theme:${id}`, target: `talk:${talk.id}`, weight: THEME_WEIGHT, type: 'topic' });
      }
    }
  }
  return { nodes, links };
}
